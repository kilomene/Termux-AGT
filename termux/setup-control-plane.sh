#!/data/data/com.termux/files/usr/bin/bash
# Termux-AGT control-plane installer — runs the ENTIRE Termux-AGT system on
# the phone itself (Termux). Android phones only: no VM, no Windows, nothing
# else.
#
# Run INSIDE Termux, from the Termux-AGT repo root, BEFORE setup-termux.sh:
#     bash termux/setup-control-plane.sh
#     bash termux/setup-termux.sh        # worker then uses the phone's API
#
# What it does:
#   1. installs Termux packages (nodejs)
#   2. copies the control-plane API + dashboard to ~/agent-host/control-plane
#      (kept in the agent-host-platform/ layout the API expects)
#   3. npm ci + npm run build (TypeScript)
#   4. writes ~/agent-host/config/control-plane.env (mode 600):
#      DATABASE_URL (your Supabase termux-agt project, direct port 5432),
#      DATA_ENCRYPTION_KEY, UAHT_PROVISIONING_TOKEN, PORT=3100
#   5. installs cloudflared (arm64) to ~/agent-host/bin and stores your
#      tunnel token at ~/agent-host/config/tunnel.token (mode 600)
#   6. smoke-tests the API against your real database (/v1/health)
#
# After this, the termux supervisor (installed by setup-termux.sh) runs
# three things: the API on 127.0.0.1:3100, cloudflared (which publishes
# https://termux.novamail.store from the phone), and the worker.
set -euo pipefail

log()  { echo "[termux-agt-cp] $*"; }
fail() { echo "[termux-agt-cp] FATAL: $*" >&2; exit 1; }

if [[ "${PREFIX:-}" != *"com.termux"* ]]; then
  fail "this installer must run inside Termux on Android (PREFIX=$PREFIX)"
fi
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
API_SRC="$REPO_DIR/agent-host-platform/control-plane/api"
DASH_SRC="$REPO_DIR/agent-host-platform/dashboard"
[ -d "$API_SRC" ] || fail "run me from the Termux-AGT repo root"

AGENT_HOME="$HOME/agent-host"
CP_HOME="$AGENT_HOME/control-plane"
CP_API="$CP_HOME/agent-host-platform/control-plane/api"
CONFIG_DIR="$AGENT_HOME/config"
BIN_DIR="$AGENT_HOME/bin"
CP_ENV="$CONFIG_DIR/control-plane.env"
TOKEN_FILE="$CONFIG_DIR/tunnel.token"
CLOUDFLARED_BIN="$BIN_DIR/cloudflared"

TAGT_PORT="3100"   # the phone's API port; the tunnel routes here

# -- 1. packages ------------------------------------------------------------
log "installing nodejs"
pkg update -y >/dev/null 2>&1 || log "pkg update had warnings; continuing"
pkg install -y nodejs \
  || fail "pkg install failed; check your network and re-run"
command -v node >/dev/null || fail "node still missing after install"
node -e 'const [m]=process.versions.node.split(".").map(Number); if (m < 18) { throw new Error("node >= 18 required") }' \
  || fail "node >= 18 is required"
log "node $(node --version) OK"

# -- 2. control-plane code ----------------------------------------------------
log "installing control-plane code to $CP_HOME"
mkdir -p "$CP_HOME/agent-host-platform/control-plane" "$CONFIG_DIR" "$BIN_DIR" \
         "$AGENT_HOME/logs"
rm -rf "$CP_API"
cp -r "$API_SRC" "$CP_API"
rm -rf "$CP_HOME/agent-host-platform/dashboard"
cp -r "$DASH_SRC" "$CP_HOME/agent-host-platform/dashboard"

# -- 3. build -----------------------------------------------------------------
log "npm ci (takes a few minutes on a phone)"
cd "$CP_API"
npm ci --no-audit --no-fund || fail "npm ci failed"
log "building (tsc)"
npm run build || fail "npm run build failed"
[ -f "$CP_API/dist/index.js" ] || fail "build did not produce dist/index.js"

# -- 4. env ----------------------------------------------------------------------
if [ -s "$CP_ENV" ]; then
  log "control-plane.env already exists; keeping it (delete it to re-enter values)"
else
  echo
  echo "I need four values. Nothing is echoed back or stored anywhere else."
  read -r -p "Supabase DATABASE_URL (termux-agt project, DIRECT port 5432): " DB_URL
  [ -n "$DB_URL" ] || fail "DATABASE_URL is required"
  read -r -p "DATA_ENCRYPTION_KEY [Enter to generate]: " DEK
  if [ -z "$DEK" ]; then
    DEK="$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')"
    log "generated DATA_ENCRYPTION_KEY"
  fi
  [ "${#DEK}" = "64" ] || fail "DATA_ENCRYPTION_KEY must be 64 hex chars"
  read -r -p "Provisioning token [Enter to generate]: " PROV
  if [ -z "$PROV" ]; then
    PROV="$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')"
    log "generated provisioning token"
  fi
  cat > "$CP_ENV" <<EOF
# Termux-AGT control-plane config — generated by termux/setup-control-plane.sh
DATABASE_URL=$DB_URL
DATA_ENCRYPTION_KEY=$DEK
UAHT_PROVISIONING_TOKEN=$PROV
PORT=$TAGT_PORT
EOF
  chmod 600 "$CP_ENV"
  log "control-plane.env written (mode 600)"
  echo
  echo "=================================================================="
  echo " SAVE THIS PROVISIONING TOKEN — the phone worker needs it next:"
  echo
  echo "   $PROV"
  echo
  echo " (also stored in $CP_ENV)"
  echo "=================================================================="
  echo
fi

# -- 5. cloudflared ---------------------------------------------------------------
# MUST be the Termux package (Android-native build). The precompiled
# linux-arm64 binary from GitHub cannot resolve DNS on Android — every lookup
# fails with "server misbehaving" on [::1]:53 (verified on-device 2026-10-10).
if command -v cloudflared >/dev/null 2>&1; then
  CLOUDFLARED_BIN="$(command -v cloudflared)"
  log "cloudflared already installed: $CLOUDFLARED_BIN"
else
  log "installing cloudflared via Termux package"
  pkg install -y cloudflared || fail "pkg install cloudflared failed"
  CLOUDFLARED_BIN="$(command -v cloudflared)" \
    || fail "cloudflared not found after install"
fi
"$CLOUDFLARED_BIN" --version >/dev/null 2>&1 \
  || fail "cloudflared does not run on this phone (see output above)"
log "cloudflared OK: $("$CLOUDFLARED_BIN" --version 2>/dev/null | head -1)"

if [ -s "$TOKEN_FILE" ]; then
  log "tunnel.token already exists; keeping it"
else
  read -r -s -p "Cloudflare tunnel token (from your termux-agt tunnel): " TUN_TOKEN; echo
  [ -n "$TUN_TOKEN" ] || fail "tunnel token is required"
  printf '%s' "$TUN_TOKEN" > "$TOKEN_FILE"
  chmod 600 "$TOKEN_FILE"
  log "tunnel token stored (mode 600)"
fi

# -- 6. smoke test: boot the API against the REAL database ---------------------------
log "smoke-testing the API against your database (migrations apply at startup)"
set -a
# shellcheck disable=SC1091
source "$CP_ENV"
set +a
PORT="$TAGT_PORT" timeout 90 node "$CP_API/dist/index.js" >"$AGENT_HOME/logs/cp-smoke.log" 2>&1 &
SMOKE_PID=$!
OK=0
for _ in $(seq 1 80); do
  if curl -sf -m 3 "http://127.0.0.1:$TAGT_PORT/v1/health" >/dev/null 2>&1; then
    OK=1; break
  fi
  sleep 1
done
kill "$SMOKE_PID" 2>/dev/null || true
wait "$SMOKE_PID" 2>/dev/null || true
if [ "$OK" = "1" ]; then
  HEALTH="$(curl -s -m 5 "http://127.0.0.1:$TAGT_PORT/v1/health" || true)"
  log "API booted against your database: $HEALTH"
else
  echo "---- $AGENT_HOME/logs/cp-smoke.log (tail) ----"
  tail -30 "$AGENT_HOME/logs/cp-smoke.log"
  fail "API did not answer /v1/health within 80s — check DATABASE_URL (direct port 5432) and network.
       If your network is IPv4-only, the direct hostname may not resolve: in the Supabase
       dashboard (termux-agt -> Database settings) enable the IPv4 add-on, or use the
       SESSION-mode pooler URI instead (never the transaction-mode pooler)."
fi

echo
echo "=================================================================="
echo " Control plane installed on this phone. Next:"
echo "   bash termux/setup-termux.sh"
echo " The supervisor will then run: API (:3100) + cloudflared tunnel +"
echo " worker — all on the phone, kept alive across reboots."
echo " Public URL (once cloudflared connects): https://termux.novamail.store"
echo "=================================================================="
